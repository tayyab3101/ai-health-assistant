@app.route('/download-report')
def download_report():

    pdf_path = "health_report.pdf"

    doc = SimpleDocTemplate(pdf_path)
    styles = getSampleStyleSheet()
    elements = []

    # Title
    elements.append(Paragraph("AI Smart Health Report", styles['Title']))
    elements.append(Spacer(1, 20))

    # DATA
    fields = [
        ("Name", request.args.get('name')),
        ("Gender", request.args.get('gender')),
        ("Age", request.args.get('age')),
        ("BMI", request.args.get('bmi')),
        ("Category", request.args.get('category')),
        ("Suggestion", request.args.get('suggestion')),
        ("Food", request.args.get('food')),
        ("Calories", request.args.get('calories')),
    ]

    for label, value in fields:
        elements.append(Paragraph(f"<b>{label}:</b> {value}", styles['BodyText']))
        elements.append(Spacer(1, 10))

    elements.append(Spacer(1, 20))
    elements.append(Paragraph("Generated by AI Smart Health Assistant", styles['Italic']))

    doc.build(elements)

    return send_file(pdf_path, as_attachment=True)

