@app.route('/result', methods=['POST'])
def result():

    try:
        name = request.form.get('name')
        gender = request.form.get('gender')
        age = request.form.get('age')
        height = float(request.form.get('height'))
        weight = float(request.form.get('weight'))
        goal = request.form.get('goal')
        allergy = request.form.get('allergy')

        # BMI
        bmi = weight / (height ** 2)

        if bmi < 18.5:
            category = "Underweight"
            suggestion = "You should gain weight 💪"
        elif bmi < 25:
            category = "Normal"
            suggestion = "Maintain your health 👍"
        else:
            category = "Overweight"
            suggestion = "You should lose weight 🏃"

        # IMAGE
        image = request.files['food_image']

        upload_folder = os.path.join(os.getcwd(), "uploads")
        os.makedirs(upload_folder, exist_ok=True)

        unique_name = str(uuid.uuid4()) + "_" + image.filename
        filepath = os.path.join(upload_folder, unique_name)
        image.save(filepath)

        # FOOD DETECTION
        try:
            ai_result = classifier(filepath)
            food = ai_result[0]['label']
            confidence = round(ai_result[0]['score'] * 100, 2)
        except:
            food = "Food"
            confidence = 0

        # CALORIES API
        cal_api_key = "RzWiBf5e4HYdn1pP/semXg==QBP99Idram2UvGSX"
        url = f"https://api.calorieninjas.com/v1/nutrition?query={food}"

        calories = "Not Found"

        try:
            response = requests.get(url, headers={'X-Api-Key': cal_api_key})
            data = response.json()

            if data.get('items'):
                calories = data['items'][0]['calories']
        except:
            calories = "Error"

        return render_template(
            "result.html",
            name=name,
            gender=gender,
            age=age,
            bmi=round(bmi, 2),
            category=category,
            suggestion=suggestion,
            goal=goal,
            allergy=allergy,
            food_name=food,
            calories=calories,
            confidence=confidence
        )

    except Exception as e:
        return f"ERROR: {str(e)}"

